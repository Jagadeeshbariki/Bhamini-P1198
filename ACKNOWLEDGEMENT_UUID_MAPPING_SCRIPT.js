/**
 * GOOGLE APPS SCRIPT: ACKNOWLEDGEMENT ID & UUID MAPPING SERVICE
 * 
 * Purpose:
 * Links each generated Acknowledgement ID (e.g. P1198-BHM-2026-001001) with its 
 * corresponding ODK / System Submission UUID and Beneficiary details.
 * 
 * Targets the SAME Google Spreadsheet used for Uploaded Letters Tracking by creating
 * or writing to a dedicated separate tab: "Ack_UUID_Mapping".
 * 
 * INSTRUCTIONS:
 * 1. Open your Google Spreadsheet (the one used for Uploaded Letters Tracking).
 * 2. In Google Sheets, click "Extensions" > "Apps Script".
 * 3. In the Apps Script editor, click the "+" next to Files and add a new Script (e.g. "AckUuidMapping.gs").
 *    (Alternatively, you can create a separate Apps Script project and set SPREADSHEET_ID below).
 * 4. Paste this complete code into the file.
 * 5. If this script is NOT container-bound to the spreadsheet, fill in SPREADSHEET_ID below.
 *    If it IS bound inside the spreadsheet, you can leave SPREADSHEET_ID as empty string.
 * 6. Click "Deploy" > "New deployment":
 *    - Select type: "Web app"
 *    - Description: "Acknowledgement ID & UUID Mapping Service"
 *    - Execute as: "Me"
 *    - Who has access: "Anyone"
 *    - Click "Deploy" and authorize permissions.
 * 7. Copy the Web App URL and paste it into config.ts as ACKNOWLEDGEMENT_MAPPING_SCRIPT_URL.
 */

// Optional: Set your Spreadsheet ID here if running from an external standalone Apps Script project.
// If this script is opened via Extensions > Apps Script inside your spreadsheet, leave it empty.
const SPREADSHEET_ID = ''; 

// Name of the tab in the spreadsheet
const SHEET_NAME = 'Ack_UUID_Mapping';

function getSpreadsheet() {
  if (typeof SPREADSHEET_ID !== 'undefined' && SPREADSHEET_ID && SPREADSHEET_ID.trim() !== '') {
    return SpreadsheetApp.openById(SPREADSHEET_ID.trim());
  }
  return SpreadsheetApp.getActiveSpreadsheet();
}

/**
 * Ensures that the dedicated mapping tab exists with proper headers, formatting and freezing.
 */
function getOrCreateMappingSheet() {
  const ss = getSpreadsheet();
  let sheet = ss.getSheetByName(SHEET_NAME);
  
  if (!sheet) {
    sheet = ss.insertSheet(SHEET_NAME);
    
    // Setup Headers
    const headers = [
      'Timestamp',
      'UUID',
      'Acknowledgement ID',
      'Beneficiary ID',
      'Beneficiary Name',
      'Activity',
      'Cluster',
      'GP',
      'Village',
      'Generated By',
      'Remarks'
    ];
    
    sheet.appendRow(headers);
    
    // Style Header Row
    const headerRange = sheet.getRange(1, 1, 1, headers.length);
    headerRange.setBackground('#1e1b4b'); // Deep indigo
    headerRange.setFontColor('#ffffff');
    headerRange.setFontWeight('bold');
    headerRange.setFontSize(10);
    headerRange.setHorizontalAlignment('center');
    
    // Freeze header row and auto-resize columns
    sheet.setFrozenRows(1);
    sheet.setRowHeight(1, 36);
  }
  
  return sheet;
}

/**
 * Handles POST requests to record new Acknowledgement ID <-> UUID links.
 * Accepts both single record payloads and batch items arrays.
 */
function doPost(e) {
  try {
    let body = {};
    if (e && e.postData && e.postData.contents) {
      try {
        body = JSON.parse(e.postData.contents);
      } catch (jsonErr) {
        body = (e && e.parameter) ? e.parameter : {};
      }
    } else if (e && e.parameter) {
      body = e.parameter;
    } else {
      return createResponse("error", "Empty POST request body", { success: false });
    }
    
    const sheet = getOrCreateMappingSheet();
    
    // Support either { items: [...] } or a single object payload
    const items = Array.isArray(body.items) ? body.items : [body];
    
    if (items.length === 0) {
      return createResponse("error", "No items provided to map", { success: false });
    }
    
    // Read existing data to prevent duplicate UUID or Acknowledgement ID rows
    const dataRange = sheet.getDataRange();
    const existingValues = dataRange.getValues();
    
    // Map of existing UUID -> row index (1-based)
    const existingUuidMap = {};
    const existingAckMap = {};
    for (let r = 1; r < existingValues.length; r++) {
      const u = String(existingValues[r][1] || '').trim();
      const a = String(existingValues[r][2] || '').trim();
      if (u) existingUuidMap[u] = r + 1;
      if (a) existingAckMap[a] = r + 1;
    }
    
    let addedCount = 0;
    let updatedCount = 0;
    const now = new Date();
    
    for (let i = 0; i < items.length; i++) {
      const item = items[i];
      const uuid = String(item.uuid || item.activityStatusUuid || item.submissionId || item.id || '').trim();
      const ackId = String(item.acknowledgementId || item.acknowledgement_number || item.ackId || '').trim();
      
      if (!uuid && !ackId) continue;
      
      const benId = String(item.beneficiaryId || item.beneficiary_id || item.farmerId || item.hhId || '').trim();
      const benName = String(item.beneficiaryName || item.beneficiary_name || item.name || '').trim();
      const activity = String(item.activityName || item.activity_name || item.activity || '').trim();
      const cluster = String(item.cluster || '').trim();
      const gp = String(item.gp || '').trim();
      const village = String(item.village || '').trim();
      const generatedBy = String(item.generatedBy || item.uploadedBy || item.user || 'System').trim();
      const remarks = String(item.remarks || 'Letter Generated').trim();
      
      const rowData = [
        now,
        uuid,
        ackId,
        benId,
        benName,
        activity,
        cluster,
        gp,
        village,
        generatedBy,
        remarks
      ];
      
      // Check if this record already exists
      const existingRow = existingUuidMap[uuid] || existingAckMap[ackId];
      if (existingRow) {
        // Update existing row
        sheet.getRange(existingRow, 1, 1, rowData.length).setValues([rowData]);
        updatedCount++;
      } else {
        // Append new row
        sheet.appendRow(rowData);
        if (uuid) existingUuidMap[uuid] = sheet.getLastRow();
        if (ackId) existingAckMap[ackId] = sheet.getLastRow();
        addedCount++;
      }
    }
    
    return createResponse("success", "Acknowledgement and UUID mappings processed successfully", {
      success: true,
      added: addedCount,
      updated: updatedCount,
      totalProcessed: items.length
    });
    
  } catch (err) {
    return createResponse("error", "Failed to save mapping: " + err.toString(), { 
      success: false 
    });
  }
}

/**
 * Handles GET requests to search and retrieve mappings by Acknowledgement ID, UUID, or search term.
 * 
 * Query parameters supported:
 * - ?q=... (searches across Ack ID, UUID, Beneficiary ID, and Name)
 * - ?ackId=... (search by exact or partial Acknowledgement ID)
 * - ?uuid=... (search by exact or partial UUID)
 * - ?beneficiaryId=... (search by Beneficiary ID)
 */
function doGet(e) {
  try {
    const sheet = getOrCreateMappingSheet();
    const rows = sheet.getDataRange().getValues();
    
    if (rows.length <= 1) {
      return createResponse("success", "No mapping records found", { records: [], total: 0 });
    }
    
    const params = (e && e.parameter) ? e.parameter : {};
    const query = String(params.q || params.query || '').toLowerCase().trim();
    const filterAck = String(params.ackId || params.acknowledgementId || '').toLowerCase().trim();
    const filterUuid = String(params.uuid || '').toLowerCase().trim();
    const filterBenId = String(params.beneficiaryId || params.farmerId || '').toLowerCase().trim();
    
    const records = [];
    
    // Iterate from row 1 (skipping header at row 0)
    for (let i = 1; i < rows.length; i++) {
      const r = rows[i];
      const timestamp = r[0] ? new Date(r[0]).toISOString() : '';
      const uuid = String(r[1] || '').trim();
      const ackId = String(r[2] || '').trim();
      const benId = String(r[3] || '').trim();
      const benName = String(r[4] || '').trim();
      const activity = String(r[5] || '').trim();
      const cluster = String(r[6] || '').trim();
      const gp = String(r[7] || '').trim();
      const village = String(r[8] || '').trim();
      const generatedBy = String(r[9] || '').trim();
      const remarks = String(r[10] || '').trim();
      
      const record = {
        timestamp: timestamp,
        uuid: uuid,
        acknowledgementId: ackId,
        beneficiaryId: benId,
        beneficiaryName: benName,
        activity: activity,
        cluster: cluster,
        gp: gp,
        village: village,
        generatedBy: generatedBy,
        remarks: remarks
      };
      
      // Apply filters if specified
      if (filterAck && !ackId.toLowerCase().includes(filterAck)) continue;
      if (filterUuid && !uuid.toLowerCase().includes(filterUuid)) continue;
      if (filterBenId && !benId.toLowerCase().includes(filterBenId)) continue;
      
      if (query) {
        const matchesQuery = 
          ackId.toLowerCase().includes(query) ||
          uuid.toLowerCase().includes(query) ||
          benId.toLowerCase().includes(query) ||
          benName.toLowerCase().includes(query) ||
          village.toLowerCase().includes(query) ||
          activity.toLowerCase().includes(query);
          
        if (!matchesQuery) continue;
      }
      
      records.push(record);
    }
    
    // Reverse to show most recent first
    records.reverse();
    
    return createResponse("success", "Fetched mapping records successfully", {
      success: true,
      records: records,
      total: records.length
    });
    
  } catch (err) {
    return createResponse("error", "Error querying mappings: " + err.toString(), { 
      success: false, 
      records: [] 
    });
  }
}

/**
 * Handles CORS Preflight
 */
function doOptions(e) {
  var headers = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Methods": "POST, GET, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Access-Control-Max-Age": "86400"
  };
  return ContentService.createTextOutput("OK").setMimeType(ContentService.MimeType.TEXT);
}

/**
 * Standard JSON response builder
 */
function createResponse(status, message, extra = {}) {
  const response = { status: status, message: message, ...extra };
  return ContentService.createTextOutput(JSON.stringify(response))
    .setMimeType(ContentService.MimeType.JSON);
}
